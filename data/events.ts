/**
 * ============================================================================
 *  SG LIVE — CURATED EVENT DATA
 * ============================================================================
 *
 * This is the single source of truth for the whole app. There is no backend and
 * nothing is scraped at runtime: every entry below was researched by hand and
 * carries a `sourceUrl` pointing at where its date was verified.
 *
 * HOW TO EDIT
 *   1. Add / amend / remove entries in `events` below.
 *   2. Bump `LAST_UPDATED` to the date you did the research (ISO `YYYY-MM-DD`).
 *   3. Run `npm run typecheck` — the discriminated union will catch a music
 *      genre applied to a sports event and vice versa.
 *
 * You do NOT need to delete past events. `getUpcoming()` in `lib/filters.ts`
 * prunes anything finished and anything beyond a rolling 12-month horizon, both
 * measured from today, so the site ages gracefully between refreshes.
 *
 * CONVENTIONS
 *   - `id`        kebab-case, unique, becomes the `/events/[slug]` URL.
 *   - `startDate` ISO `YYYY-MM-DD`. Add `endDate` only for multi-day runs.
 *   - `status`    'confirmed'    date + venue locked, tickets generally on sale
 *                 'on-sale-soon' announced, tickets not yet released
 *                 'tbc'          edition expected, date/venue/lineup unconfirmed
 *   - `featured`  reserve for genuinely marquee events; drives the hero rotation.
 *   - `palette`   see `lib/gradients.ts`. Loosely genre-led so the grid reads as
 *                 one designed set. There is no artwork to source — all event
 *                 imagery is generated CSS, never a hotlinked promo image.
 *
 * SCOPE
 *   Singapore listings cover international (non-local) touring acts plus the
 *   marquee sports calendar. Local Singaporean artists are intentionally out of
 *   scope. The regional block covers major festivals elsewhere in Southeast Asia.
 *
 * KNOWN GAP
 *   Club-night bookings (Zouk, Marquee, CÉ LA VI) are announced only ~4–6 weeks
 *   ahead, so House/Techno entries are always thinner in the back half of the
 *   window. That genre needs the most frequent refresh — see the README.
 */

